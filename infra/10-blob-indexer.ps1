#requires -Version 7.0
<#
  Creates the pull-model pipeline for main-assets-index:

    ADLS Gen2 (jsonl/)  ->  data source  ->  indexer + embedding skillset  ->  index

  Replaces the push model in scripts/ingest.ps1. Vectors are generated by the
  Azure OpenAI embedding skill rather than in PowerShell, so nothing has to run
  from a laptop.

  Prerequisites:
    - scripts/to-jsonl.py has produced and uploaded jsonl/*.jsonl
    - run once with -Prepare to grant RBAC and establish the private link

  Usage:
    ./10-blob-indexer.ps1 -Prepare      # RBAC + shared private link + approval
    ./10-blob-indexer.ps1 -Run          # create objects and index
    ./10-blob-indexer.ps1 -SkipCreate   # status only
#>
param(
    [switch]$Prepare,      # grant RBAC and create/approve the shared private links
    [switch]$Run,          # kick off the indexer immediately after creating it
    [switch]$SkipCreate    # only report status
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

# --- Config ---
$searchSvc   = 'libraaisearch'
$searchRg    = 'hokiepurview'
$indexName   = 'main-assets-index'
$api         = '2024-07-01'
$base        = "https://$searchSvc.search.windows.net"

$storageAcc  = 'hokiesynapseadls03'
$storageRg   = 'hokiesynapse'
$container   = 'main-assets'
$folder      = 'jsonl'

$aoaiBase    = 'https://hokieopenai.openai.azure.com'
$embedDeploy = 'text-embedding-3-large'
$dimensions  = 3072

$dsName      = 'main-assets-jsonl-ds'
$skillsetName= 'main-assets-embed-skillset'
$indexerName = 'main-assets-indexer'

$key = az search admin-key show -g $searchRg --service-name $searchSvc --query primaryKey -o tsv
$hdr = @{ 'api-key' = $key; 'Content-Type' = 'application/json' }
$sub = az account show --query id -o tsv

function Put([string]$Path, $Body) {
    $json = $Body | ConvertTo-Json -Depth 20
    Invoke-RestMethod -Uri "$base/$Path`?api-version=$api" -Headers $hdr -Method Put -Body $json | Out-Null
}

if ($Prepare) {
    $searchMi = az search service show -g $searchRg -n $searchSvc --query identity.principalId -o tsv
    if (-not $searchMi) { throw "$searchSvc has no system-assigned managed identity." }
    $storageId = az storage account show -g $storageRg -n $storageAcc --query id -o tsv
    $aoaiId = az cognitiveservices account list --query "[?name=='hokieopenai'] | [0].id" -o tsv

    Write-Host "Granting RBAC to the search identity ..." -ForegroundColor Cyan
    foreach ($g in @(@{ r = 'Storage Blob Data Reader'; s = $storageId }, @{ r = 'Cognitive Services OpenAI User'; s = $aoaiId })) {
        if (az role assignment list --assignee $searchMi --role $g.r --scope $g.s --query "[].id" -o tsv) {
            Write-Host "  already granted: $($g.r)"
        } else {
            az role assignment create --assignee-object-id $searchMi --assignee-principal-type ServicePrincipal `
                --role $g.r --scope $g.s -o none
            Write-Host "  granted: $($g.r)"
        }
    }

    # Storage has public access disabled, so the indexer needs an outbound
    # private link. HNS accounts are reached over dfs; blob is created too
    # because the indexer falls back to it for some operations.
    Write-Host "Creating shared private links ..." -ForegroundColor Cyan
    foreach ($group in 'blob', 'dfs') {
        $splName = "spl-$storageAcc-$group"
        if (az search shared-private-link-resource list --service-name $searchSvc -g $searchRg --query "[?name=='$splName'].name" -o tsv) {
            Write-Host "  exists: $splName"
        } else {
            az search shared-private-link-resource create --name $splName --service-name $searchSvc -g $searchRg `
                --group-id $group --resource-id $storageId --request-message "Libra Asset Search indexer" -o none
            Write-Host "  created: $splName"
        }
    }

    Write-Host "Approving pending private endpoint connections ..." -ForegroundColor Cyan
    $pending = az network private-endpoint-connection list --id $storageId `
        --query "[?properties.privateLinkServiceConnectionState.status=='Pending'].name" -o tsv
    foreach ($p in $pending) {
        az network private-endpoint-connection approve --id "$storageId/privateEndpointConnections/$p" `
            --description 'Approved for Libra Asset Search indexer' -o none
        Write-Host "  approved: $p"
    }
    if (-not $pending) { Write-Host "  none pending" }

    az search shared-private-link-resource list --service-name $searchSvc -g $searchRg `
        --query "[].{name:name, group:properties.groupId, status:properties.status}" -o table
    Write-Host ""
}

if (-not $SkipCreate) {
    # --- Data source: keyless, using the search service managed identity ---
    Write-Host "Creating data source $dsName ..." -ForegroundColor Cyan
    $dataSource = [ordered]@{
        name        = $dsName
        type        = 'adlsgen2'
        credentials = [ordered]@{
            connectionString = "ResourceId=/subscriptions/$sub/resourceGroups/$storageRg/providers/Microsoft.Storage/storageAccounts/$storageAcc/;"
        }
        container   = [ordered]@{ name = $container; query = $folder }
    }
    Put "datasources/$dsName" $dataSource

    # --- Skillset: embedding only ---
    # Deliberately a single embedding skill. Adding any other skill type would
    # push this into the S1-only bracket for private-link indexers, and the
    # text it embeds is precomputed as embedText by scripts/to-jsonl.py so the
    # vectors match what ingest.ps1 produced.
    Write-Host "Creating skillset $skillsetName ..." -ForegroundColor Cyan
    $skillset = [ordered]@{
        name        = $skillsetName
        description = 'Embeds the precomputed embedText field for main-assets-index.'
        skills      = @(
            [ordered]@{
                '@odata.type' = '#Microsoft.Skills.Text.AzureOpenAIEmbeddingSkill'
                name          = 'embed-description'
                description   = 'text-embedding-3-large over embedText'
                context       = '/document'
                resourceUri   = $aoaiBase
                deploymentId  = $embedDeploy
                modelName     = $embedDeploy
                dimensions    = $dimensions
                inputs        = @( [ordered]@{ name = 'text'; source = '/document/embedText' } )
                outputs       = @( [ordered]@{ name = 'embedding'; targetName = 'vector' } )
            }
        )
    }
    Put "skillsets/$skillsetName" $skillset

    # --- Indexer ---
    Write-Host "Creating indexer $indexerName ..." -ForegroundColor Cyan
    $indexer = [ordered]@{
        name           = $indexerName
        dataSourceName = $dsName
        targetIndexName= $indexName
        skillsetName   = $skillsetName
        parameters     = [ordered]@{
            batchSize     = 50
            maxFailedItems= 5
            configuration = [ordered]@{
                parsingMode = 'jsonLines'
                # Required whenever the source is reached over a shared private link.
                executionEnvironment = 'private'
            }
        }
        # Source property names already match index field names, so the only
        # mapping needed is the skill output.
        fieldMappings       = @()
        outputFieldMappings = @(
            [ordered]@{ sourceFieldName = '/document/vector'; targetFieldName = 'descriptionVector' }
        )
        schedule = [ordered]@{ interval = 'PT12H' }
    }
    Put "indexers/$indexerName" $indexer
    Write-Host "Created." -ForegroundColor Green
}

if ($Run) {
    Write-Host "`nRunning $indexerName ..." -ForegroundColor Cyan
    Invoke-RestMethod -Uri "$base/indexers/$indexerName/run`?api-version=$api" -Headers $hdr -Method Post | Out-Null
}

Write-Host "`n--- indexer status ---" -ForegroundColor Cyan
$st = Invoke-RestMethod -Uri "$base/indexers/$indexerName/status`?api-version=$api" -Headers $hdr
"status          : $($st.status)"
"last run status : $($st.lastResult.status)"
"items processed : $($st.lastResult.itemsProcessed)"
"items failed    : $($st.lastResult.itemsFailed)"
if ($st.lastResult.errorMessage) { "error           : $($st.lastResult.errorMessage)" }
foreach ($e in ($st.lastResult.errors | Select-Object -First 5)) { "  ERROR $($e.key): $($e.errorMessage)" }
foreach ($w in ($st.lastResult.warnings | Select-Object -First 5)) { "  WARN  $($w.key): $($w.message)" }
